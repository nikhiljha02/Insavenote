-- Older installations stored Google's external ID in notes."userId". Map it
-- to the owning users.id UUID before changing the column type.
DO $$
DECLARE
  user_id_type text;
  unmapped_notes bigint;
BEGIN
  SELECT data_type INTO user_id_type
  FROM information_schema.columns
  WHERE table_schema = current_schema()
    AND table_name = 'notes'
    AND column_name = 'userId';

  IF user_id_type IN ('text', 'character varying', 'character') THEN
    ALTER TABLE notes ADD COLUMN IF NOT EXISTS "userId_uuid_migration" uuid;

    UPDATE notes AS n
    SET "userId_uuid_migration" = u.id
    FROM users AS u
    WHERE n."userId_uuid_migration" IS NULL
      AND n."userId"::text = u.id::text;

    UPDATE notes AS n
    SET "userId_uuid_migration" = u.id
    FROM users AS u
    WHERE n."userId_uuid_migration" IS NULL
      AND n."userId"::text = u."googleId";

    SELECT COUNT(*) INTO unmapped_notes
    FROM notes
    WHERE "userId_uuid_migration" IS NULL;

    IF unmapped_notes > 0 THEN
      RAISE EXCEPTION 'Cannot migrate % note(s): their user IDs do not match a database user ID or Google ID', unmapped_notes;
    END IF;

    ALTER TABLE notes DROP COLUMN "userId";
    ALTER TABLE notes RENAME COLUMN "userId_uuid_migration" TO "userId";
  ELSIF user_id_type IS DISTINCT FROM 'uuid' THEN
    RAISE EXCEPTION 'Unsupported notes.userId type: %', user_id_type;
  END IF;
END $$;

ALTER TABLE notes ALTER COLUMN "userId" SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'notes'::regclass
      AND conname = 'notes_user_id_fkey'
  ) THEN
    ALTER TABLE notes
      ADD CONSTRAINT notes_user_id_fkey
      FOREIGN KEY ("userId") REFERENCES users(id) ON DELETE CASCADE;
  END IF;
END $$;

UPDATE notes
SET label = 'General'
WHERE label IS NULL OR BTRIM(label) = '';

UPDATE notes
SET note_encrypted = false
WHERE note_encrypted IS NULL;

UPDATE notes
SET color = 'paper-' || (FLOOR(random() * 10) + 1)::int
WHERE color IS NULL OR color NOT IN (
  'paper-1', 'paper-2', 'paper-3', 'paper-4', 'paper-5',
  'paper-6', 'paper-7', 'paper-8', 'paper-9', 'paper-10'
