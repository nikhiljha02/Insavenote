CREATE TABLE IF NOT EXISTS users (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  "googleId" text,
  name text NOT NULL,
  email text NOT NULL,
  picture text NOT NULL DEFAULT '',
  "passwordHash" text,
  created_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS "googleId" text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS name text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS picture text NOT NULL DEFAULT '';
ALTER TABLE users ADD COLUMN IF NOT EXISTS "passwordHash" text;
ALTER TABLE users ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();

CREATE UNIQUE INDEX IF NOT EXISTS users_google_id_unique_idx
  ON users ("googleId");

CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique_idx
  ON users (lower(email));

CREATE TABLE IF NOT EXISTS notes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" text NOT NULL,
  note text NOT NULL,
  note_encrypted boolean NOT NULL DEFAULT false,
  label text NOT NULL DEFAULT 'General',
  color text NOT NULL DEFAULT ('paper-' || (FLOOR(random() * 10) + 1)::int),
  locked boolean NOT NULL DEFAULT false,
  password text
);

ALTER TABLE notes ADD COLUMN IF NOT EXISTS "userId" text;
ALTER TABLE notes ADD COLUMN IF NOT EXISTS note text;
ALTER TABLE notes ADD COLUMN IF NOT EXISTS note_encrypted boolean NOT NULL DEFAULT false;
ALTER TABLE notes ADD COLUMN IF NOT EXISTS label text NOT NULL DEFAULT 'General';
ALTER TABLE notes ADD COLUMN IF NOT EXISTS color text;
ALTER TABLE notes ADD COLUMN IF NOT EXISTS locked boolean NOT NULL DEFAULT false;
ALTER TABLE notes ADD COLUMN IF NOT EXISTS password text;

UPDATE notes
SET label = 'General'
WHERE label IS NULL OR BTRIM(label) = '';

UPDATE notes
SET note_encrypted = false
WHERE note_encrypted IS NULL;

UPDATE notes
SET color = 'paper-' || (FLOOR(random() * 10) + 1)::int
WHERE color IS NULL OR color NOT IN (
  'paper-1', 'paper-2', 'paper-3', 'paper-4', 'paper-5',
  'paper-6', 'paper-7', 'paper-8', 'paper-9', 'paper-10'
);

ALTER TABLE notes ALTER COLUMN label SET DEFAULT 'General';
ALTER TABLE notes ALTER COLUMN label SET NOT NULL;
ALTER TABLE notes ALTER COLUMN note_encrypted SET DEFAULT false;
ALTER TABLE notes ALTER COLUMN note_encrypted SET NOT NULL;
ALTER TABLE notes
  ALTER COLUMN color SET DEFAULT ('paper-' || (FLOOR(random() * 10) + 1)::int);
ALTER TABLE notes ALTER COLUMN color SET NOT NULL;

CREATE INDEX IF NOT EXISTS notes_user_id_id_idx
  ON notes ("userId", id DESC);
