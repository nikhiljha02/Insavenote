CREATE INDEX IF NOT EXISTS notes_user_id_id_idx
  ON notes ("userId", id DESC);


CREATE TABLE IF NOT EXISTS note_password_reset_tokens (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  note_id BIGINT NOT NULL REFERENCES notes(id) ON DELETE CASCADE,
  user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS note_password_reset_tokens_expiry_idx
  ON note_password_reset_tokens (expires_at)
  WHERE used = false;
